"""Read-only current-source build gate. Execute only trusted checkout tools."""
import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MARKER = re.compile(r"<!--SC-INLINE ([A-Za-z0-9_-]+)-->")
EXEC = {"", "text/javascript", "application/javascript", "module"}
TYPE = re.compile(r'\btype\s*=\s*["\']([^"\']*)["\']', re.I)


def snapshot(root):
    result = {}
    for p in sorted(root.rglob("*")):
        if p.is_symlink():
            raise ValueError(f"symlink in source: {p}")
        if p.is_file():
            result[str(p.relative_to(root))] = hashlib.sha256(p.read_bytes()).hexdigest()
    return result


def assemble(root):
    template = (root / "src/html/index.template.html").read_bytes().decode("utf-8")
    blocks = json.loads((root / "src/html/blocks.json").read_text(encoding="utf-8"))
    if not isinstance(blocks, list) or not blocks:
        raise ValueError("empty/non-list manifest")
    ids, paths, scripts = [], set(), []
    for b in blocks:
        bid, rel = b["id"], b["file"]
        if not re.fullmatch(r"[A-Za-z0-9_-]+", bid) or bid in ids:
            raise ValueError(f"invalid or duplicate id {bid}")
        p = root / rel
        if not rel.startswith("src/") or not p.resolve().is_relative_to((root / "src").resolve()):
            raise ValueError(f"unsafe path {rel}")
        if rel in paths or not p.is_file() or p.is_symlink():
            raise ValueError(f"duplicate/missing block {rel}")
        ids.append(bid)
        paths.add(rel)
        tag, close, kind = b["open_tag"], b["close_tag"], b["element"]
        if kind not in {"script", "style"} or not re.fullmatch(r"<"+kind+r"\b[^>]*>", tag, re.I) or close.lower() != f"</{kind}>":
            raise ValueError(f"invalid block tags {bid}")
        body = p.read_bytes().decode("utf-8")
        if MARKER.search(body):
            raise ValueError(f"marker inside block {bid}")
        marker = f"<!--SC-INLINE {bid}-->"
        if template.count(marker) != 1:
            raise ValueError(f"marker count {bid}")
        t = TYPE.search(tag)
        if kind == "script" and (t.group(1).strip().lower() if t else "") in EXEC:
            if not rel.endswith(".js"):
                raise ValueError(f"unrecognized executable path {rel}")
            scripts.append((rel, bool(t and t.group(1).strip().lower()=="module")))
    if MARKER.findall(template) != ids or not scripts:
        raise ValueError("manifest/template order mismatch or zero executable blocks")
    for b in blocks:
        body = (root / b["file"]).read_bytes().decode("utf-8")
        template = template.replace(f"<!--SC-INLINE {b['id']}-->", b["open_tag"]+body+b["close_tag"], 1)
    return template.encode("utf-8"), scripts


def checked(args, cwd, timeout=90):
    subprocess.run(args, cwd=cwd, check=True, timeout=timeout)


def verify(root, require_publish_match=False):
    root = Path(root).resolve()
    before = snapshot(root / "src")
    expected, scripts = assemble(root)
    node = shutil.which("node")
    if not node:
        raise RuntimeError("BLOCKED: Node.js not installed")
    with tempfile.TemporaryDirectory(prefix="sc-build-") as tmp:
        work = Path(tmp)
        shutil.copytree(root / "src", work / "src")
        (work / "tools").mkdir()
        shutil.copy2(root / "tools/build.py", work / "tools/build.py")
        for i, (rel, module) in enumerate(scripts):
            p = work / rel
            if module:
                q = work / f"module-{i}.mjs"
                q.write_bytes(p.read_bytes())
                p = q
            checked([node, "--check", str(p)], work)
        if (root / "sw.js").is_file():
            shutil.copy2(root / "sw.js", work / "sw.js")
            checked([node, "--check", str(work / "sw.js")], work)
        elif require_publish_match:
            raise ValueError("missing sw.js")
        for _ in range(2):
            out = work / "dist/index.html"
            if out.exists():
                out.unlink()
            checked([sys.executable, str(work / "tools/build.py")], work)
            if out.read_bytes() != expected:
                raise ValueError("generated bytes differ from independent source assembly")
            if snapshot(work / "src") != before:
                raise ValueError("build mutated source")
    if snapshot(root / "src") != before:
        raise ValueError("active source changed during gate")
    publish = root / "index.html"
    equal = publish.is_file() and publish.read_bytes() == expected
    print(f"blocks parsed: {len(scripts)}; sha256: {hashlib.sha256(expected).hexdigest()}; root publish match: {equal}")
    if require_publish_match and not equal:
        raise ValueError("root publish differs from source output; no automatic overwrite")
    print("PASS current-source assembly and syntax; not gameplay/PWA QA")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--require-publish-match", action="store_true")
    args = parser.parse_args()
    try:
        verify(args.root, args.require_publish_match)
    except RuntimeError as exc:
        print(str(exc), file=sys.stderr)
        return 2
    except (ValueError, OSError, KeyError, TypeError, subprocess.SubprocessError) as exc:
        print(f"FAIL {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
